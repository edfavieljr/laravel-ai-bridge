<?php
declare(strict_types=1);

namespace Edfavieljr\LaravelAIBridge\Tests\Unit\Services;

use Edfavieljr\LaravelAIBridge\Contracts\AIServiceInterface;
use Edfavieljr\LaravelAIBridge\Exceptions\AIException;
use Edfavieljr\LaravelAIBridge\Services\HuggingFaceService;
use Edfavieljr\LaravelAIBridge\Tests\TestCase;
use Illuminate\Support\Facades\Http;

class HuggingFaceServiceTest extends TestCase
{
    protected function newService(): HuggingFaceService
    {
        return new HuggingFaceService('test-hf-key', [
            'timeout' => 5,
            'default_model' => 'gpt2',
            'default_embedding_model' => 'sentence-transformers/all-mpnet-base-v2',
        ]);
    }

    public function test_it_implements_interface(): void
    {
        $this->assertInstanceOf(AIServiceInterface::class, $this->newService());
    }

    public function test_generate_text_success(): void
    {
        Http::fake([
            'https://api-inference.huggingface.co/*' => Http::response([
                ['generated_text' => 'Generated by HuggingFace'],
            ], 200),
        ]);

        $result = $this->newService()->generateText('Hello');

        $this->assertEquals('Generated by HuggingFace', $result);
    }

    public function test_generate_text_sends_correct_headers(): void
    {
        Http::fake([
            'https://api-inference.huggingface.co/*' => Http::response([
                ['generated_text' => 'ok'],
            ], 200),
        ]);

        $this->newService()->generateText('test');

        Http::assertSent(function ($request) {
            return $request->hasHeader('Authorization', 'Bearer test-hf-key');
        });
    }

    public function test_generate_text_throws_on_api_error(): void
    {
        Http::fake([
            'https://api-inference.huggingface.co/*' => Http::response([
                'error' => 'Model is loading',
            ], 503),
        ]);

        $this->expectException(AIException::class);
        $this->newService()->generateText('test');
    }

    public function test_generate_embeddings_success(): void
    {
        Http::fake([
            'https://api-inference.huggingface.co/*' => Http::response([
                [0.1, 0.2, 0.3, 0.4],
            ], 200),
        ]);

        $result = $this->newService()->generateEmbeddings('test text');

        $this->assertIsArray($result);
    }

    public function test_generate_embeddings_throws_on_error(): void
    {
        Http::fake([
            'https://api-inference.huggingface.co/*' => Http::response([
                'error' => 'Error',
            ], 500),
        ]);

        $this->expectException(AIException::class);
        $this->newService()->generateEmbeddings('test');
    }

    public function test_analyze_sentiment_with_classification_model(): void
    {
        Http::fake([
            'https://api-inference.huggingface.co/*' => Http::response([
                [
                    ['label' => 'POSITIVE', 'score' => 0.95],
                    ['label' => 'NEGATIVE', 'score' => 0.05],
                ],
            ], 200),
        ]);

        $result = $this->newService()->analyzeSentiment('Great product!');

        $this->assertArrayHasKey('score', $result);
        $this->assertArrayHasKey('category', $result);
        $this->assertArrayHasKey('details', $result);
    }

    public function test_classify_text_with_zero_shot(): void
    {
        Http::fake([
            'https://api-inference.huggingface.co/*' => Http::response([
                'labels' => ['technology', 'sports', 'politics'],
                'scores' => [0.9, 0.07, 0.03],
            ], 200),
        ]);

        $result = $this->newService()->classifyText('AI is amazing', ['technology', 'sports', 'politics']);

        $this->assertEquals('technology', $result['category']);
        $this->assertEquals(0.9, $result['confidence']);
        $this->assertArrayHasKey('details', $result);
    }

    public function test_extract_entities_success(): void
    {
        Http::fake([
            'https://api-inference.huggingface.co/*' => Http::response([
                ['word' => 'Microsoft', 'entity' => 'B-ORG', 'score' => 0.99],
                ['word' => 'Seattle', 'entity' => 'B-LOC', 'score' => 0.95],
            ], 200),
        ]);

        $result = $this->newService()->extractEntities('Microsoft is based in Seattle');

        $this->assertIsArray($result);
        $this->assertCount(2, $result);
    }

    public function test_generate_image_returns_base64(): void
    {
        Http::fake([
            'https://api-inference.huggingface.co/*' => Http::response('fake-image-binary-data', 200),
        ]);

        $result = $this->newService()->generateImage('A cat');

        $this->assertStringStartsWith('data:image/jpeg;base64,', $result);
    }

    public function test_generate_image_throws_on_error(): void
    {
        Http::fake([
            'https://api-inference.huggingface.co/*' => Http::response([
                'error' => 'Model error',
            ], 500),
        ]);

        $this->expectException(AIException::class);
        $this->newService()->generateImage('test');
    }

    public function test_model_method_sets_model(): void
    {
        Http::fake([
            'https://api-inference.huggingface.co/*' => Http::response([
                ['generated_text' => 'ok'],
            ], 200),
        ]);

        $this->newService()->model('facebook/opt-1.3b')->generateText('test');

        Http::assertSent(function ($request) {
            return str_contains($request->url(), 'facebook/opt-1.3b');
        });
    }

    public function test_get_client_returns_http_client(): void
    {
        $this->assertNotNull($this->newService()->getClient());
    }
}
